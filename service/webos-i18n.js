    var locale = 'en';

    function normalize(value) {
        // Stremio stores the interface language as an ISO 639-2 code such as eng, pob or por
        var language = String(value || '').trim().toLowerCase().replace(/_/g, '-');
        if (language === 'pt-br' || language === 'pob' || language === 'por' || language === 'pt') return 'pt-BR';
        if (language === 'en-us' || language === 'eng') return 'en';
        return 'en';
    }

    function text(key, params) {
        // The current language first, English for a missing key, the key itself as the last resort
        var selected = dictionaries[locale] || dictionaries.en;
        var value = selected[key] || dictionaries.en[key] || key;
        return value.replace(/\{([a-zA-Z0-9_]+)\}/g, function (match, name) {
            var replacement = params && params[name];
            return typeof replacement === 'string' || typeof replacement === 'number' || typeof replacement === 'boolean' ? String(replacement) : match;
        });
    }

    function number(value, digits) {
        // Fixed decimals with the separator of the current language
        var fixed = Number(value).toFixed(digits);
        return locale === 'pt-BR' ? fixed.replace('.', ',') : fixed;
    }

    function refresh() {
        // Read the interface language from the Stremio profile; a missing core keeps the current one
        if (!window.core || typeof window.core.getState !== 'function') return Promise.resolve(locale);
        try {
            return Promise.resolve(window.core.getState('ctx')).then(function (ctx) {
                var settings = ctx && ctx.profile && ctx.profile.settings;
                locale = normalize(settings && settings.interfaceLanguage);
                return locale;
            }).catch(function () { return locale; });
        } catch (_e) {
            return Promise.resolve(locale);
        }
    }

    window.__twkI18n = { t: text, number: number, refresh: refresh, language: function () { return locale; } };
    refresh();
